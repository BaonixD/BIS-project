"""Migration procedure on a fresh SQLite file: empty -> head -> no diff.

Synchronous on purpose: Alembic's env.py runs its own event loop.
"""

import asyncio
from pathlib import Path

import pytest
from alembic import command
from alembic.config import Config
from sqlalchemy import text

from taxi_service.database.migrations import alembic_config, current_revisions, expected_heads
from taxi_service.database.session import create_database_engine

BASELINE_REVISION = "dea9719c6061"  # T01: empty starting point of the history
T03_HEAD = "e87ec15b6147"  # driver_profiles and vehicles; the revision before ride tables
RIDE_TABLES = {"ride_quotes", "rides", "idempotency_records"}


@pytest.fixture
def config(tmp_path: Path) -> Config:
    return alembic_config(
        f"sqlite+aiosqlite:///{tmp_path / 'migrations-test.db'}", configure_logging=False
    )


def database_state(config: Config) -> tuple[frozenset[str], list[str]]:
    async def read() -> tuple[frozenset[str], list[str]]:
        engine = create_database_engine(config.attributes["database_url"])
        try:
            async with engine.connect() as connection:
                revisions = await current_revisions(connection)
                tables = await connection.scalars(
                    text("SELECT name FROM sqlite_master WHERE type = 'table' ORDER BY name")
                )
                return revisions, list(tables)
        finally:
            await engine.dispose()

    return asyncio.run(read())


def execute(config: Config, sql: str) -> list[tuple[object, ...]]:
    async def run() -> list[tuple[object, ...]]:
        engine = create_database_engine(config.attributes["database_url"])
        try:
            async with engine.begin() as connection:
                result = await connection.execute(text(sql))
                return [tuple(row) for row in result] if result.returns_rows else []
        finally:
            await engine.dispose()

    return asyncio.run(run())


def test_history_has_single_head() -> None:
    assert len(expected_heads()) == 1


def test_upgrade_empty_database_to_head_without_diff(config: Config) -> None:
    assert database_state(config) == (frozenset(), [])

    command.upgrade(config, "head")

    revisions, tables = database_state(config)
    assert revisions
    assert revisions == expected_heads()
    assert "alembic_version" in tables
    command.check(config)  # raises AutogenerateDiffsDetected on any model/schema drift


def test_repeated_upgrade_is_a_no_op(config: Config) -> None:
    command.upgrade(config, "head")
    migrated = database_state(config)

    command.upgrade(config, "head")

    assert database_state(config) == migrated


def test_downgrade_to_base_and_upgrade_again(config: Config) -> None:
    command.upgrade(config, "head")

    command.downgrade(config, "base")
    assert database_state(config)[0] == frozenset()

    command.upgrade(config, "head")
    revisions, _ = database_state(config)
    assert revisions
    assert revisions == expected_heads()


def test_upgrade_from_t01_baseline_creates_auth_tables(config: Config) -> None:
    command.upgrade(config, BASELINE_REVISION)
    assert database_state(config) == (frozenset({BASELINE_REVISION}), ["alembic_version"])

    command.upgrade(config, "head")

    _, tables = database_state(config)
    assert {"users", "auth_sessions"} <= set(tables)
    command.check(config)


def test_downgrade_one_step_and_upgrade_again(config: Config) -> None:
    command.upgrade(config, "head")
    _, head_tables = database_state(config)

    command.downgrade(config, "-1")
    revisions, tables = database_state(config)
    assert revisions != expected_heads()
    assert "users" in tables
    # The last revision drops payment_events, so its downgrade brings a table back.
    assert set(tables) ^ set(head_tables) == {"payment_events"}

    command.upgrade(config, "head")
    assert database_state(config) == (expected_heads(), head_tables)


def test_ride_tables_upgrade_and_downgrade_keep_existing_users(config: Config) -> None:
    command.upgrade(config, T03_HEAD)
    execute(
        config,
        "INSERT INTO users (id, username, username_normalized, password_hash, role, created_at)"
        " VALUES ('0f1e2d3c4b5a69788796a5b4c3d2e1f0', 'pat', 'pat', 'hash', 'passenger',"
        " '2026-11-03 09:00:00.000000')",
    )

    command.upgrade(config, "head")

    _, tables = database_state(config)
    assert set(tables) >= RIDE_TABLES
    assert execute(config, "SELECT username FROM users") == [("pat",)]
    command.check(config)

    command.downgrade(config, T03_HEAD)

    _, tables = database_state(config)
    assert not set(tables) & RIDE_TABLES
    assert execute(config, "SELECT username FROM users") == [("pat",)]
