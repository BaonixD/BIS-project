"""Migration procedure on a fresh SQLite file: empty -> head -> no diff.

Synchronous on purpose: Alembic's env.py runs its own event loop.
"""

import asyncio
from pathlib import Path

import pytest
from alembic import command
from alembic.config import Config
from sqlalchemy import text

from taxi_service.database.migrations import alembic_config, current_revisions, expected_heads
from taxi_service.database.session import create_database_engine


@pytest.fixture
def config(tmp_path: Path) -> Config:
    return alembic_config(f"sqlite+aiosqlite:///{tmp_path / 'migrations-test.db'}")


def database_state(config: Config) -> tuple[frozenset[str], list[str]]:
    async def read() -> tuple[frozenset[str], list[str]]:
        engine = create_database_engine(config.attributes["database_url"])
        try:
            async with engine.connect() as connection:
                revisions = await current_revisions(connection)
                tables = await connection.scalars(
                    text("SELECT name FROM sqlite_master WHERE type = 'table' ORDER BY name")
                )
                return revisions, list(tables)
        finally:
            await engine.dispose()

    return asyncio.run(read())


def test_history_has_single_head() -> None:
    assert len(expected_heads()) == 1


def test_upgrade_empty_database_to_head_without_diff(config: Config) -> None:
    assert database_state(config) == (frozenset(), [])

    command.upgrade(config, "head")

    revisions, tables = database_state(config)
    assert revisions
    assert revisions == expected_heads()
    assert "alembic_version" in tables
    command.check(config)  # raises AutogenerateDiffsDetected on any model/schema drift


def test_repeated_upgrade_is_a_no_op(config: Config) -> None:
    command.upgrade(config, "head")
    migrated = database_state(config)

    command.upgrade(config, "head")

    assert database_state(config) == migrated


def test_downgrade_to_base_and_upgrade_again(config: Config) -> None:
    command.upgrade(config, "head")

    command.downgrade(config, "base")
    assert database_state(config)[0] == frozenset()

    command.upgrade(config, "head")
    revisions, _ = database_state(config)
    assert revisions
    assert revisions == expected_heads()
