KAZAKH_LETTERS: Final = frozenset("әғқңөұүһіӘҒҚҢӨҰҮҺІ")
LANGUAGE_NAMES: Final = {"ru": "русский", "kk": "казахский", "en": "английский"}


def reply_language(text: str) -> str:
    """``kk`` for Kazakh letters, ``en`` for mostly Latin text, otherwise ``ru``."""
    if any(char in KAZAKH_LETTERS for char in text):
        return "kk"
    latin = sum(char.isascii() and char.isalpha() for char in text)
    cyrillic = sum("а" <= char.lower() <= "я" or char.lower() == "ё" for char in text)
    return "en" if latin > cyrillic else "ru"


def ticket_context(
    prompt: str, role: UserRole, category: str, *, linked_ride: bool, question: str
) -> str:
    about = [
        f"Пользователь — {ROLE_NAMES.get(role, 'пользователь')}.",
        f"Категория обращения — {CATEGORY_NAMES.get(category, category)}.",
        f"Язык ответа — {LANGUAGE_NAMES[reply_language(question)]}.",
    ]
    if linked_ride:
        about.append("Обращение привязано к поездке; её данных у тебя нет.")
    return f"{prompt}\n\nКонтекст обращения: {' '.join(about)}\n\nСправка TezJet:\n{KNOWLEDGE}"


def with_subject(subject: str, body: str) -> str:
    return f"{body}\n\n[Тема: {subject}]"
